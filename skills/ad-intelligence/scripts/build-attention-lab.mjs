#!/usr/bin/env node
/**
 * Embed attention-models.json into examples/visual/attention-data.js for the lab.
 * Usage: node scripts/build-attention-lab.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const src = path.join(ROOT, "references", "attention-models.json");
const dest = path.join(ROOT, "examples", "visual", "attention-data.js");

const data = JSON.parse(fs.readFileSync(src, "utf8"));
const out = `/* auto-generated by scripts/build-attention-lab.mjs — do not edit by hand */\nwindow.AD_INTEL_ATTENTION = ${JSON.stringify(data, null, 2)};\n`;
fs.writeFileSync(dest, out);
console.error(`Wrote ${dest} (${out.length} bytes, ${data.models.length} models)`);
